-- ADR-014 Phase 1: the policy module OWNS the `policy` schema (ADR-006 schema-per-module), folding in the
-- PAS registry from ktayl-policy-service. Flyway's default-schema is `billing` (its history lives there),
-- so this migration EXPLICITLY creates + qualifies the `policy` schema. Phase 1 covers the bind-path core
-- (create → submit → activate, the lifecycle, the DORA-Art.9 audit log). Coverages / premium-metadata /
-- documents / CloudEvents / attestation PDF are Phase 1b (defined in the SPEC, carried forward from the PAS).
CREATE SCHEMA IF NOT EXISTS policy;

CREATE TABLE policy.policy (
    id             uuid         PRIMARY KEY,
    policy_number  varchar(64)  NOT NULL UNIQUE,           -- the shared key, deterministic from the quote
    holder_name    varchar(256) NOT NULL,
    product_code   varchar(64)  NOT NULL,
    status         varchar(16)  NOT NULL DEFAULT 'DRAFT',
    effective_date date         NOT NULL,
    expiry_date    date         NOT NULL,
    created_at     timestamptz  NOT NULL DEFAULT now(),
    updated_at     timestamptz  NOT NULL DEFAULT now(),
    CONSTRAINT chk_policy_dates  CHECK (effective_date < expiry_date),
    CONSTRAINT chk_policy_status CHECK (status IN ('DRAFT','SUBMITTED','ACTIVE','AMENDED','CANCELLED','EXPIRED','REJECTED'))
);
CREATE INDEX idx_policy_status ON policy.policy (status);

-- DORA Art.9 (BF-POL-03): one immutable row per lifecycle transition — who, from→to, why, when.
CREATE TABLE policy.policy_audit_log (
    id          bigint      GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    policy_id   uuid        NOT NULL REFERENCES policy.policy (id),
    action      varchar(32) NOT NULL,
    from_status varchar(16) NOT NULL,
    to_status   varchar(16) NOT NULL,
    actor_id    varchar(128) NOT NULL,
    reason      varchar(256),
    at          timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX idx_policy_audit_policy ON policy.policy_audit_log (policy_id);
