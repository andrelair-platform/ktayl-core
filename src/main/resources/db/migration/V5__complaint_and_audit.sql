-- CMPL-011 — the real complaint register + the module's append-only audit log, in the complaints schema
-- (ADR-006 schema-per-module). Maps to com.ktayl.core.complaints.infrastructure.persistence.*Entity; the
-- domain aggregate (Complaint) is separate and pure (hexagonal, ADR-013). The schema_marker from V4 stays
-- as the baseline sentinel.

CREATE TABLE complaints.complaint (
    id              uuid PRIMARY KEY,
    channel         varchar(16)  NOT NULL,          -- ComplaintChannel (PHONE|EMAIL|PORTAL|LETTER|BROKER)
    subject_ref     varchar(128),                   -- party/policy by reference, never a cross-schema FK (ADR-006)
    summary         text         NOT NULL,
    status          varchar(16)  NOT NULL,          -- ComplaintStatus (REGISTERED|ACKNOWLEDGED|…)
    registered_at   timestamptz  NOT NULL,
    idempotency_key varchar(128)                     -- client safe-retry key; unique when present
);

-- Idempotent POST retries: at most one complaint per supplied key (NULLs are allowed/non-unique in PG).
CREATE UNIQUE INDEX ux_complaint_idempotency_key
    ON complaints.complaint (idempotency_key)
    WHERE idempotency_key IS NOT NULL;

CREATE TABLE complaints.audit_log (
    id        bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    entity    varchar(64)  NOT NULL,
    entity_id varchar(64)  NOT NULL,
    action    varchar(64)  NOT NULL,
    actor     varchar(128) NOT NULL,
    detail    text,
    at        timestamptz  NOT NULL
);

CREATE INDEX ix_complaint_audit_entity ON complaints.audit_log (entity, entity_id);
