-- RC-02 S1: the screening module OWNS the `screening` schema (ADR-006 schema-per-module). AML/sanctions
-- screening (LCB-FT / DORA) gating a party at a business gate (intake/bind/payment). Flyway's default-schema
-- is `billing` (its history lives there), so this migration EXPLICITLY creates + qualifies the `screening`
-- schema. S1 covers the screen → fail-closed-HOLD → alert → HITL case decision path + the append-only audit.
CREATE SCHEMA IF NOT EXISTS screening;

-- A party put through screening (the natural/legal person being checked). `ids` is a JSON string kept as
-- plain text (S1 keeps it simple — not jsonb); `ubo_of` is a free-text back-reference for a UBO link.
CREATE TABLE screening.party (
    id           uuid        PRIMARY KEY,
    external_ref text,
    name         text        NOT NULL,
    dob          date,
    nationality  text,
    residence    text,
    ids          text,
    ubo_of       text,
    created_at   timestamptz NOT NULL DEFAULT now()
);

-- One screening event: a party checked at a gate, producing a verdict. ALLOW = no hit; HOLD = at least one
-- hit OR a fail-closed (engine outage → HOLD, dataset_version null). dataset_version pins the list version used.
CREATE TABLE screening.screening (
    id              uuid        PRIMARY KEY,
    party_id        uuid        NOT NULL REFERENCES screening.party (id),
    gate            varchar(32) NOT NULL,
    at              timestamptz NOT NULL DEFAULT now(),
    dataset_version varchar(64),
    verdict         varchar(8)  NOT NULL CHECK (verdict IN ('ALLOW','HOLD'))
);
CREATE INDEX idx_screening_party ON screening.screening (party_id);

-- One alert per hit returned by the engine, bucketed by match type. S1 only emits SANCTION (sanctions lists);
-- PEP/AME/RISK_COUNTRY/UBO/ORIAS buckets are later increments but the CHECK allows them already.
CREATE TABLE screening.alert (
    id            uuid        PRIMARY KEY,
    screening_id  uuid        NOT NULL REFERENCES screening.screening (id),
    bucket        varchar(16) NOT NULL CHECK (bucket IN ('SANCTION','PEP','AME','RISK_COUNTRY','UBO','ORIAS')),
    score         int         NOT NULL,
    matched_entry text
);
CREATE INDEX idx_alert_screening ON screening.alert (screening_id);

-- The HITL decision on an alert (named `screening_case` because CASE is a SQL keyword). One case per alert.
-- A human compliance officer accepts/refuses, grades the risk + vigilance level, and records a rationale.
CREATE TABLE screening.screening_case (
    id         uuid         PRIMARY KEY,
    alert_id   uuid         NOT NULL UNIQUE REFERENCES screening.alert (id),
    status     varchar(8)   NOT NULL CHECK (status IN ('ACC','REF','PENDING')),
    risk       varchar(8)   CHECK (risk IN ('WEAK','MED','STRONG')),
    vigilance  varchar(8)   CHECK (vigilance IN ('NORMAL','ENHANCED')),
    actor_id   varchar(128),
    rationale  varchar(512),
    decided_at timestamptz
);

-- LCB-FT / DORA append-only audit — one immutable row per screening action (SCREEN / SCREEN_FAILCLOSED /
-- DECIDE). Only INSERTed; keep >= 5 years. No FK so an audit row survives any later data change.
CREATE TABLE screening.screening_audit (
    id              bigint       GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    party_id        uuid,
    action          varchar(32)  NOT NULL,
    actor_id        varchar(128) NOT NULL,
    dataset_version varchar(64),
    detail          text,
    at              timestamptz  NOT NULL DEFAULT now()
);
CREATE INDEX idx_screening_audit_party ON screening.screening_audit (party_id);
